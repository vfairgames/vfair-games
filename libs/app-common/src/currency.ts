export const currencyStep = (decimals: number): number => 10 ** -decimals;

type FormatCurrencyOptions = {
  currency: Currency | string;
  locale?: string;
  decimals?: number;
  showSymbol?: boolean;
};

export const formatCurrency = (
  amount: number,
  { currency, locale, decimals = 2, showSymbol = true }: FormatCurrencyOptions,
): string => {
  const resolvedLocale =
    locale ?? CURRENCY_LOCALE_MAP[currency as Currency] ?? 'en-US';
  const roundedAmount = roundToDecimals(amount, decimals);

  if (!showSymbol) {
    return new Intl.NumberFormat(resolvedLocale, {
      style: 'decimal',
      minimumFractionDigits: decimals,
      maximumFractionDigits: decimals,
    }).format(roundedAmount);
  }

  return new Intl.NumberFormat(resolvedLocale, {
    style: 'currency',
    currency,
    currencyDisplay: 'symbol',
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(roundedAmount);
};
